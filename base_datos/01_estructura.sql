-- Compatible con las 20 tablas creadas durante la actividad. No borra datos.
CREATE DATABASE IF NOT EXISTS atlantic_city CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE atlantic_city;

CREATE TABLE IF NOT EXISTS AREAS (
    IdArea VARCHAR(10) PRIMARY KEY,
    Area VARCHAR(100) NOT NULL UNIQUE) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS CARGOS (
    IdCargo VARCHAR(10) PRIMARY KEY,
    Cargo VARCHAR(100) NOT NULL UNIQUE,
    IdArea VARCHAR(10) NOT NULL,
    FOREIGN KEY (IdArea) REFERENCES AREAS(IdArea)) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS EMPLEADOS (
    IdEmpleado VARCHAR(10) PRIMARY KEY,
    Nombres VARCHAR(60) NOT NULL,
    Apellidos VARCHAR(80) NOT NULL,
    DNI CHAR(8) NOT NULL UNIQUE,
    Correo VARCHAR(100),
    Telefono VARCHAR(20),
    IdCargo VARCHAR(10) NOT NULL,
    Estado CHAR(1) NOT NULL DEFAULT 'A',
    FOREIGN KEY (IdCargo) REFERENCES CARGOS(IdCargo)) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS USUARIOS (
    IdUsuario VARCHAR(10) PRIMARY KEY,
    IdEmpleado VARCHAR(10) NOT NULL UNIQUE,
    NombreUsuario VARCHAR(50) NOT NULL UNIQUE,
    ClaveHash VARCHAR(255) NOT NULL,
    Rol VARCHAR(30) NOT NULL,
    Estado CHAR(1) NOT NULL DEFAULT 'A',
    FOREIGN KEY (IdEmpleado) REFERENCES EMPLEADOS(IdEmpleado)) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS SEGMENTOS_CLIENTES (
    IdSegmento VARCHAR(10) PRIMARY KEY,
    Segmento VARCHAR(30) NOT NULL UNIQUE) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS DEPARTAMENTOS (
    CodigoDepartamento CHAR(2) PRIMARY KEY,
    Departamento VARCHAR(100) NOT NULL) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS PROVINCIAS (
    CodigoProvincia CHAR(4) PRIMARY KEY,
    Provincia VARCHAR(100) NOT NULL,
    CodigoDepartamento CHAR(2) NOT NULL,
    FOREIGN KEY (CodigoDepartamento) REFERENCES DEPARTAMENTOS(CodigoDepartamento)) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS UBIGEO (
    CodigoUbigeo CHAR(6) PRIMARY KEY,
    Distrito VARCHAR(100) NOT NULL,
    CodigoProvincia CHAR(4) NOT NULL,
    FOREIGN KEY (CodigoProvincia) REFERENCES PROVINCIAS(CodigoProvincia)) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS CLIENTES (
    IdCliente VARCHAR(10) PRIMARY KEY,
    Nombres VARCHAR(60) NOT NULL,
    Apellidos VARCHAR(80) NOT NULL,
    TipoDocumento VARCHAR(30) NOT NULL,
    NumeroDocumento VARCHAR(20) NOT NULL,
    PaisEmisorDocumento VARCHAR(60) NOT NULL,
    Nacionalidad VARCHAR(50) NOT NULL,
    Telefono VARCHAR(20),
    Correo VARCHAR(100) NOT NULL,
    CodigoUbigeo CHAR(6),
    Direccion VARCHAR(150),
    FechaRegistro DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    IdSegmento VARCHAR(10) NOT NULL,
    IdUsuarioRegistro VARCHAR(10) NOT NULL,
    Estado CHAR(1) NOT NULL DEFAULT 'A',
    UNIQUE (TipoDocumento,NumeroDocumento,PaisEmisorDocumento),
    FOREIGN KEY (CodigoUbigeo) REFERENCES UBIGEO(CodigoUbigeo),
    FOREIGN KEY (IdSegmento) REFERENCES SEGMENTOS_CLIENTES(IdSegmento),
    FOREIGN KEY (IdUsuarioRegistro) REFERENCES USUARIOS(IdUsuario)) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS VISITAS (
    IdVisita VARCHAR(10) PRIMARY KEY,
    IdCliente VARCHAR(10) NOT NULL,
    IdUsuarioRegistro VARCHAR(10) NOT NULL,
    FechaHoraInicio DATETIME NOT NULL,
    FechaHoraFin DATETIME,
    Observacion VARCHAR(250),
    FOREIGN KEY (IdCliente) REFERENCES CLIENTES(IdCliente),
    FOREIGN KEY (IdUsuarioRegistro) REFERENCES USUARIOS(IdUsuario)) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS TIPOS_JUEGO (
    IdTipoJuego VARCHAR(10) PRIMARY KEY,
    TipoJuego VARCHAR(60) NOT NULL UNIQUE) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS JUEGOS (
    IdJuego VARCHAR(10) PRIMARY KEY,
    Nombre VARCHAR(100) NOT NULL,
    Descripcion VARCHAR(250),
    IdTipoJuego VARCHAR(10) NOT NULL,
    Estado CHAR(1) NOT NULL DEFAULT 'A',
    FOREIGN KEY (IdTipoJuego) REFERENCES TIPOS_JUEGO(IdTipoJuego)) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS DETALLES_VISITAS (
    IdDetalleVisita VARCHAR(10) PRIMARY KEY,
    IdVisita VARCHAR(10) NOT NULL,
    IdJuego VARCHAR(10) NOT NULL,
    CantidadPartidas INT NOT NULL,
    Gasto DECIMAL(10,2) NOT NULL,
    Premio DECIMAL(10,2) NOT NULL,
    Resultado VARCHAR(10) NOT NULL,
    Inconveniente VARCHAR(200),
    FOREIGN KEY (IdVisita) REFERENCES VISITAS(IdVisita),
    FOREIGN KEY (IdJuego) REFERENCES JUEGOS(IdJuego)) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS METODOS_PAGO (
    IdMetodoPago VARCHAR(10) PRIMARY KEY,
    MetodoPago VARCHAR(50) NOT NULL UNIQUE,
    Estado CHAR(1) NOT NULL DEFAULT 'A' ) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS PAGOS (
    IdPago VARCHAR(10) PRIMARY KEY,
    IdDetalleVisita VARCHAR(10) NOT NULL,
    TipoPago VARCHAR(30) NOT NULL,
    FechaHoraPago DATETIME NOT NULL,
    MontoPagado DECIMAL(10,2) NOT NULL,
    IdMetodoPago VARCHAR(10) NOT NULL,
    IdUsuarioRegistro VARCHAR(10) NOT NULL,
    ReferenciaOperacion VARCHAR(100),
    FOREIGN KEY (IdDetalleVisita) REFERENCES DETALLES_VISITAS(IdDetalleVisita),
    FOREIGN KEY (IdMetodoPago) REFERENCES METODOS_PAGO(IdMetodoPago),
    FOREIGN KEY (IdUsuarioRegistro) REFERENCES USUARIOS(IdUsuario)) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS PROMOCIONES (
    IdPromocion VARCHAR(10) PRIMARY KEY,
    Nombre VARCHAR(100) NOT NULL,
    Descripcion VARCHAR(500),
    FechaInicio DATE NOT NULL,
    FechaFin DATE NOT NULL,
    Estado CHAR(1) NOT NULL DEFAULT 'A',
    Beneficio VARCHAR(250),
    Condiciones VARCHAR(500),
    Restricciones VARCHAR(500),
    MaxUsosPorCliente INT NOT NULL) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS CLIENTES_PROMOCIONES (
    IdAsignacion VARCHAR(10) PRIMARY KEY,
    IdCliente VARCHAR(10) NOT NULL,
    IdPromocion VARCHAR(10) NOT NULL,
    FechaAsignacion DATETIME NOT NULL,
    FOREIGN KEY (IdCliente) REFERENCES CLIENTES(IdCliente),
    FOREIGN KEY (IdPromocion) REFERENCES PROMOCIONES(IdPromocion)) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS USOS_PROMOCIONES (
    IdUso VARCHAR(10) PRIMARY KEY,
    IdAsignacion VARCHAR(10) NOT NULL,
    IdDetalleVisita VARCHAR(10) NOT NULL,
    FechaUso DATETIME NOT NULL,
    FOREIGN KEY (IdAsignacion) REFERENCES CLIENTES_PROMOCIONES(IdAsignacion),
    FOREIGN KEY (IdDetalleVisita) REFERENCES DETALLES_VISITAS(IdDetalleVisita)) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS ATENCIONES (
    IdAtencion VARCHAR(10) PRIMARY KEY,
    IdCliente VARCHAR(10) NOT NULL,
    IdEmpleado VARCHAR(10) NOT NULL,
    TipoAtencion VARCHAR(50) NOT NULL,
    FechaAtencion DATETIME NOT NULL,
    Asunto VARCHAR(100) NOT NULL,
    Descripcion VARCHAR(600) NOT NULL,
    Estado VARCHAR(20) NOT NULL DEFAULT 'Pendiente',
    FechaSolucion DATETIME,
    Solucion VARCHAR(600),
    IdUsuarioRegistro VARCHAR(10) NOT NULL,
    IdVisita VARCHAR(10),
    FOREIGN KEY (IdCliente) REFERENCES CLIENTES(IdCliente),
    FOREIGN KEY (IdEmpleado) REFERENCES EMPLEADOS(IdEmpleado),
    FOREIGN KEY (IdUsuarioRegistro) REFERENCES USUARIOS(IdUsuario),
    FOREIGN KEY (IdVisita) REFERENCES VISITAS(IdVisita)) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS SEGUIMIENTOS_ATENCIONES (
    IdSeguimiento VARCHAR(10) PRIMARY KEY,
    IdAtencion VARCHAR(10) NOT NULL,
    FechaSeguimiento DATETIME NOT NULL,
    Estado VARCHAR(20) NOT NULL,
    Respuesta VARCHAR(600) NOT NULL,
    IdUsuarioRegistro VARCHAR(10) NOT NULL,
    FOREIGN KEY (IdAtencion) REFERENCES ATENCIONES(IdAtencion),
    FOREIGN KEY (IdUsuarioRegistro) REFERENCES USUARIOS(IdUsuario)) ENGINE=InnoDB;

